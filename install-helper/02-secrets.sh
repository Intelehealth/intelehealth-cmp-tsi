#!/usr/bin/env bash
# Service account, directories and the service env file ($CONF_DIR/tsi-cms.env).
# Secrets are generated once and never overwritten; settings that come from
# install.conf are refreshed on every run.
. "$(dirname "$0")/lib.sh"
require_root

step 'Service account and directories'
getent group "$APP_USER" >/dev/null || groupadd --system "$APP_USER"
id -u "$APP_USER" >/dev/null 2>&1 \
  || useradd --system --gid "$APP_USER" --home-dir "$DATA_DIR" --no-create-home --shell /usr/sbin/nologin "$APP_USER"
install -d -m 0750 -o root -g "$APP_USER" "$CONF_DIR"
install -d -m 0750 -o "$APP_USER" -g "$APP_USER" "$DATA_DIR" "$EXPORT_DIR"
install -d -m 0700 -o root -g root "$BACKUP_DIR"
ok "User $APP_USER; $CONF_DIR, $EXPORT_DIR, $BACKUP_DIR ready."

step 'Service env file'
if [ ! -f "$ENV_FILE" ]; then
  install -m 0640 -o root -g "$APP_USER" /dev/null "$ENV_FILE"
  cat > "$ENV_FILE" <<EOF
# TSI DPDP CMS service settings - read by systemd (EnvironmentFile=).
# Generated by install-helper/02-secrets.sh. KEY=value, no quotes.
# Optional settings (SMTP_*, SMS_GATEWAY_URL, SSO_*, DIGILOCKER_VERIFY_URL ...)
# are documented in .env.example; add them here, then:
#   systemctl restart tsi-cms-app tsi-cms-worker
EOF
  created=1
else
  created=0
fi

# Secrets: only filled when missing. NEVER change DB_ENCRYPTION_KEY,
# TSI_LOOKUP_SALT or PII_LOOKUP_KEY once data exists.
env_set_default POSTGRES_PASSWD "$(new_secret)"
env_set_default JWT_SECRET "$(new_secret)"
env_set_default DB_ENCRYPTION_KEY "$(new_secret)"
env_set_default TSI_LOOKUP_SALT "$(new_secret)"
env_set_default PII_LOOKUP_KEY "$(new_secret)"
env_set_default BOOTSTRAP_TOKEN "$(new_secret)"
env_set_default HEALTHZ_TOKEN "$(new_secret)"
# Set explicitly so it never silently follows DB_ENCRYPTION_KEY (signed
# certificates would otherwise depend on that key forever).
env_set_default CERTIFICATE_SIGNING_KEY "$(new_secret)"

# Settings from install.conf (refreshed each run).
origins="$ALLOWED_ORIGINS"
if [ -z "$origins" ]; then
  if [ -n "$DOMAIN" ]; then origins="https://$DOMAIN"; else origins="http://127.0.0.1:$APP_PORT"; fi
fi
proxies="127.0.0.1,::1"
[ -z "$EXTRA_TRUSTED_PROXY_IPS" ] || proxies="$proxies,$EXTRA_TRUSTED_PROXY_IPS"
# 03-postgres.sh rewrites the port once the cluster exists.
env_set_default POSTGRES_HOST "postgresql://127.0.0.1:5432"
env_set POSTGRES_DB "$DB_NAME"
env_set POSTGRES_USER "$DB_USER"
env_set TSI_DPDP_CMS_ENV "$APP_ENV"
env_set TSI_EXPORT_PATH "$EXPORT_DIR/"
env_set ALLOWED_ORIGINS "$origins"
env_set TRUSTED_PROXY_IPS "$proxies"
if [ -n "$OUTBOUND_ALLOWED_HOSTS" ]; then env_set OUTBOUND_ALLOWED_HOSTS "$OUTBOUND_ALLOWED_HOSTS"; fi
if [ -n "$BRAND_NAME" ]; then env_set BRAND_NAME "$BRAND_NAME"; fi
env_set_default WORKER_POLL_SECONDS 30
env_set_default WORKER_BATCH_SIZE 50
env_set_default NOTIFICATION_RETRY_LIMIT 5
env_set_default WEBHOOK_RETRY_LIMIT 5
env_set_default ALERT_ESCALATION_HOURS 24
env_set_default PURGE_NOTICE_HOURS 48
env_set_default GRIEVANCE_ESCALATION_HOURS 24
chown root:"$APP_USER" "$ENV_FILE"; chmod 0640 "$ENV_FILE"

if [ "$created" = "1" ]; then
  ok "$ENV_FILE written with generated secrets."
  printf '\n%s' "$C_YELLOW"
  cat <<EOF
  IMPORTANT: back up $ENV_FILE now, OFFLINE and away from the database backups.
  Losing DB_ENCRYPTION_KEY loses who every consent belongs to; anyone holding
  it together with a database dump can read all principal identifiers.
  See docs/security/KEY_MANAGEMENT.md.
EOF
  printf '%s' "$C_OFF"
else
  ok "$ENV_FILE updated (existing secrets kept)."
fi
